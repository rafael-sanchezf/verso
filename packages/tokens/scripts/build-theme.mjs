#!/usr/bin/env node
/**
 * Generates the app's theme from `tokens.json`.
 *
 * `tokens.json` is exported from the Figma file and is the only place a value
 * is allowed to be written by hand-free means (see README.md). This script
 * turns it into the two forms code consumes:
 *
 *   src/theme.ts   a typed theme module: light and dark colors, spacing,
 *                  radius, and the ten-style type ramp, as numbers React
 *                  Native can use directly.
 *   theme.css      the CSS custom properties, named exactly as the tokens'
 *                  `$extensions.verso.css`, in a Tailwind v4 `@theme` block
 *                  so the styling layer (Uniwind / NativeWind on Tailwind v4)
 *                  generates utilities from the same values.
 *
 * Both outputs are committed so CI needs no build step; `pnpm tokens:build`
 * regenerates them and CI fails if they are stale. Never edit the outputs.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, '..');

const tokens = JSON.parse(readFileSync(join(pkgRoot, 'tokens.json'), 'utf8'));

const GENERATED = 'Generated by packages/tokens/scripts/build-theme.mjs from tokens.json. Do not edit.';

/** `$extensions.verso` on a token, or an empty object. */
function ext(token) {
  return token?.$extensions?.verso ?? {};
}

/** `12px` -> 12. React Native sizes are unitless density-independent points. */
function px(value) {
  const n = Number(String(value).replace(/px$/, ''));
  if (!Number.isFinite(n)) throw new Error(`not a px dimension: ${value}`);
  return n;
}

// ---------------------------------------------------------------------------
// Colors
// ---------------------------------------------------------------------------

/**
 * Flat color entries keyed the way the specs name them (`bg/canvas`,
 * `text/primary`, `brand/primary`), so a line in docs/design/specs maps to a
 * line of code with no translation table.
 */
const colors = [];
for (const [group, members] of Object.entries(tokens.color)) {
  for (const [name, token] of Object.entries(members)) {
    const { css, modes } = ext(token);
    colors.push({
      key: `${group}/${name}`,
      css,
      light: (modes?.light ?? token.$value).toUpperCase(),
      dark: (modes?.dark ?? token.$value).toUpperCase(),
      description: token.$description ?? '',
    });
  }
}

const space = Object.entries(tokens.space).map(([name, token]) => ({
  key: name,
  css: ext(token).css,
  value: px(token.$value),
}));

const radius = Object.entries(tokens.radius).map(([name, token]) => ({
  key: name,
  css: ext(token).css,
  value: px(token.$value),
}));

const font = Object.entries(tokens.font).map(([name, token]) => ({
  key: name,
  family: token.$value.fontFamily,
  weight: token.$value.fontWeight,
  size: px(token.$value.fontSize),
  lineHeight: px(token.$value.lineHeight),
}));

// ---------------------------------------------------------------------------
// src/theme.ts
// ---------------------------------------------------------------------------

const quote = (s) => `'${s.replace(/'/g, "\\'")}'`;

/** A union written one member per line, so a diff shows which token moved. */
const union = (members) => members.map((m) => `\n  | ${m}`).join('');

const colorUnion = union(colors.map((c) => quote(c.key)));
const spaceUnion = space.map((s) => s.key).join(' | ');
const radiusUnion = radius.map((r) => quote(r.key)).join(' | ');
const fontUnion = union(font.map((f) => quote(f.key)));

function colorBlock(mode) {
  return colors
    .map((c) => `  ${quote(c.key)}: '${c[mode]}',${c.description ? ` // ${c.description}` : ''}`)
    .join('\n');
}

const themeTs = `/**
 * ${GENERATED}
 *
 * Colors are keyed the way docs/design/specs names them, so \`bg/canvas\` in a
 * spec is \`theme.colors['bg/canvas']\` in code. Sizes are points.
 */

export type ColorToken =${colorUnion};

export type SpaceToken = ${spaceUnion};

export type RadiusToken = ${radiusUnion};

export type FontStyle =${fontUnion};

export type ColorScheme = 'light' | 'dark';

/** One text style off the ten-style ramp, ready for a React Native \`TextStyle\`. */
export interface TypeStyle {
  fontFamily: string;
  fontWeight: ${[...new Set(font.map((f) => f.weight))].sort().join(' | ')};
  fontSize: number;
  lineHeight: number;
}

export interface Theme {
  scheme: ColorScheme;
  colors: Record<ColorToken, string>;
  space: Record<SpaceToken, number>;
  radius: Record<RadiusToken, number>;
  font: Record<FontStyle, TypeStyle>;
}

const lightColors: Record<ColorToken, string> = {
${colorBlock('light')}
};

const darkColors: Record<ColorToken, string> = {
${colorBlock('dark')}
};

/** Spacing steps, in points. \`space[4]\` is the 16pt side padding the specs use. */
export const space: Record<SpaceToken, number> = {
${space.map((s) => `  ${s.key}: ${s.value},`).join('\n')}
};

export const radius: Record<RadiusToken, number> = {
${radius.map((r) => `  ${quote(r.key)}: ${r.value},`).join('\n')}
};

/**
 * The ten text styles. \`fontFamily\` is the family name; the app maps a family
 * plus a weight onto the loaded Inter face (see src/ui/text.tsx).
 */
export const font: Record<FontStyle, TypeStyle> = {
${font
  .map(
    (f) =>
      `  ${quote(f.key)}: { fontFamily: ${quote(f.family)}, fontWeight: ${f.weight}, fontSize: ${f.size}, lineHeight: ${f.lineHeight} },`,
  )
  .join('\n')}
};

export const lightTheme: Theme = { scheme: 'light', colors: lightColors, space, radius, font };
export const darkTheme: Theme = { scheme: 'dark', colors: darkColors, space, radius, font };

export const themes: Record<ColorScheme, Theme> = { light: lightTheme, dark: darkTheme };

/** Every color token name, for the preview gallery and for runtime checks. */
export const COLOR_TOKENS = [
${colors.map((c) => `  ${quote(c.key)},`).join('\n')}
] as const;

/** Every text style name, best first, as the ramp is ordered in Figma. */
export const FONT_STYLES = [
${font.map((f) => `  ${quote(f.key)},`).join('\n')}
] as const;

/** The CSS custom property a token is published as, for the web build. */
export const CSS_VARIABLES: Record<ColorToken, string> = {
${colors.map((c) => `  ${quote(c.key)}: ${quote(c.css)},`).join('\n')}
};
`;

// ---------------------------------------------------------------------------
// theme.css
// ---------------------------------------------------------------------------

const themeCss = `/* ${GENERATED} */

/*
 * Tailwind v4 reads its design tokens from CSS custom properties in \`@theme\`,
 * so these names are both the variables the web build resolves and the source
 * of the generated utilities (\`--color-bg-canvas\` gives \`bg-bg-canvas\`).
 * Light is the base; the dark block re-points the same names, which is why
 * every utility follows the color scheme without a second class.
 */
@theme {
${colors.map((c) => `  ${c.css}: ${c.light};`).join('\n')}

${space.map((s) => `  ${s.css}: ${s.value}px;`).join('\n')}

${radius.map((r) => `  ${r.css}: ${r.value}px;`).join('\n')}

${font.map((f) => `  --text-${f.key}: ${f.size}px;\n  --text-${f.key}--line-height: ${f.lineHeight}px;\n  --text-${f.key}--font-weight: ${f.weight};`).join('\n')}

  --font-sans: '${font[0].family}', ui-sans-serif, system-ui, sans-serif;
}

@media (prefers-color-scheme: dark) {
  :root {
${colors.map((c) => `    ${c.css}: ${c.dark};`).join('\n')}
  }
}

:root[data-theme='dark'],
.dark {
${colors.map((c) => `  ${c.css}: ${c.dark};`).join('\n')}
}
`;

mkdirSync(join(pkgRoot, 'src'), { recursive: true });
writeFileSync(join(pkgRoot, 'src', 'theme.ts'), themeTs);
writeFileSync(join(pkgRoot, 'theme.css'), themeCss);

console.log(
  `tokens: wrote src/theme.ts and theme.css (${colors.length} colors, ${space.length} spaces, ${radius.length} radii, ${font.length} text styles)`,
);
